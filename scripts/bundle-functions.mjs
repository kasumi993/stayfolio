// Copies shared code into the edge functions that use it. A deployed function
// cannot import from a sibling folder or from src/, so each gets its own copy;
// imports get the ".ts" extension Deno needs. Run after changing src/core or
// supabase/functions/_shared: node scripts/bundle-functions.mjs
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';

const HEADER = '// Generated by scripts/bundle-functions.mjs from the app\'s sources. Do not edit here.\n';
const fix = (s) => s.replace(/from '(\.\/[a-z]+)'/g, "from '$1.ts'");
const copy = (from, to) => writeFileSync(to, HEADER + fix(readFileSync(from, 'utf8')));

for (const fn of ['member-invite', 'monthly-report']) copy('supabase/functions/_shared/mail.ts', `supabase/functions/${fn}/mail.ts`);
mkdirSync('supabase/functions/monthly-report/core', { recursive: true });
for (const f of ['types', 'dates', 'calc', 'member', 'recurring', 'id']) copy(`src/core/${f}.ts`, `supabase/functions/monthly-report/core/${f}.ts`);
console.log('bundled');
